"""Reproducible synthetic-data fraud ML research experiment.

IMPORTANT: Synthetic labels are generated by a programmed heuristic. Metrics only
describe this synthetic exercise and must never be quoted as real fraud accuracy.
No user data or banking data is used.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import numpy as np
from joblib import dump
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import average_precision_score, brier_score_loss, precision_recall_fscore_support, roc_auc_score
from sklearn.calibration import CalibratedClassifierCV
from sklearn.frozen import FrozenEstimator

FEATURE_NAMES = [
    "amount_minor_log10", "new_beneficiary", "new_device", "failed_logins_1h",
    "server_velocity_1h", "account_age_days", "device_age_days", "geo_change",
]
SEED = 63821

def synthetic_dataset(n=6000, seed=SEED):
    rng = np.random.default_rng(seed)
    X = np.column_stack([
        rng.uniform(0, 7, n),
        rng.binomial(1, .12, n),
        rng.binomial(1, .15, n),
        rng.poisson(.5, n),
        rng.poisson(1.7, n),
        rng.exponential(280, n).clip(0, 2500),
        rng.exponential(80, n).clip(0, 1000),
        rng.binomial(1, .08, n),
    ]).astype(float)
    # Synthetic probability is not a model of actual fraud prevalence.
    logit = -5 + .35 * X[:, 0] + .95 * X[:, 1] + .7 * X[:, 2] + .24 * X[:, 3] + .2 * X[:, 4] - .002 * X[:, 5] + .65 * X[:, 7]
    p = 1 / (1 + np.exp(-logit))
    y = (rng.uniform(0, 1, n) < p).astype(int)
    return X, y

def train(output_dir: Path, n=6000):
    if n < 500:
        raise ValueError("Dataset must contain >=500 synthetic examples")
    X, y = synthetic_dataset(n)
    # Deterministic chronological-style partition (training/calibration/test). Synthetic
    # sample order represents event order, not real observed time.
    train_end, calibration_end = int(.60 * n), int(.80 * n)
    Xtrain, ytrain = X[:train_end], y[:train_end]
    Xcal, ycal = X[train_end:calibration_end], y[train_end:calibration_end]
    Xtest, ytest = X[calibration_end:], y[calibration_end:]
    base = HistGradientBoostingClassifier(max_iter=90, max_leaf_nodes=13, learning_rate=.065, l2_regularization=2,
                                          random_state=SEED)
    base.fit(Xtrain, ytrain)
    calibrated = CalibratedClassifierCV(FrozenEstimator(base), method="sigmoid")
    calibrated.fit(Xcal, ycal)
    scores = calibrated.predict_proba(Xtest)[:, 1]
    threshold = .35  # illustrative threshold, not optimized for any real organization's loss
    predictions = (scores >= threshold).astype(int)
    precision, recall, f1, _ = precision_recall_fscore_support(ytest, predictions, average="binary", zero_division=0)
    results = {
        "dataset": "synthetic_labels_only", "seed": SEED, "size": n,
        "feature_names": FEATURE_NAMES, "split": {"train": train_end, "calibration": calibration_end-train_end,
                                                  "test": n-calibration_end},
        "synthetic_positive_rate_test": round(float(ytest.mean()), 5),
        "average_precision": round(float(average_precision_score(ytest, scores)), 5),
        "roc_auc": round(float(roc_auc_score(ytest, scores)), 5),
        "brier_score": round(float(brier_score_loss(ytest, scores)), 5),
        "threshold": threshold, "precision": round(float(precision), 5),
        "recall": round(float(recall), 5), "f1": round(float(f1), 5),
        "disclaimer": "NO real-world fraud accuracy or bias claims: generated synthetic labels only.",
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    dump({"model": calibrated, "features": FEATURE_NAMES, "disclaimer": results["disclaimer"]}, output_dir / "synthetic_fraud_model.joblib")
    (output_dir / "metrics.json").write_text(json.dumps(results, indent=2) + "\n")
    return results

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path("ml/artifacts"))
    parser.add_argument("--rows", type=int, default=6000)
    args = parser.parse_args()
    print(json.dumps(train(args.output, args.rows), indent=2))
